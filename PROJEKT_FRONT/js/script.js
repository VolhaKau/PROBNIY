// ЯЗЫКОВОЕ МЕНЮ + ВОССТАНОВЛЕНИЕ ЯЗЫКА
// ============================================================
document.addEventListener('DOMContentLoaded', () => {
  const dropdown = document.getElementById('languageDropdown');
  const currentLangBtn = document.getElementById('currentLangBtn');
  const langMenu = document.getElementById('langMenu');
  const currentFlag = document.getElementById('currentFlagImg');

  if (dropdown && currentLangBtn && langMenu) {
    currentLangBtn.addEventListener('click', (e) => {
      e.stopPropagation();
      langMenu.classList.toggle('show');
      currentLangBtn.setAttribute('aria-expanded', langMenu.classList.contains('show'));
    });

    document.querySelectorAll('.lang-option').forEach(option => {
      option.addEventListener('click', () => {
        const selectedLang = option.getAttribute('data-lang');
        const flagInOption = option.querySelector('.flag');
        if (currentFlag && flagInOption) currentFlag.src = flagInOption.src;

        langMenu.classList.remove('show');
        currentLangBtn.setAttribute('aria-expanded', 'false');
        translatePage(selectedLang);
      });
    });

    document.addEventListener('click', (e) => {
      if (!dropdown.contains(e.target)) {
        langMenu.classList.remove('show');
        currentLangBtn.setAttribute('aria-expanded', 'false');
      }
    });
  }

  // Восстановление языка при загрузке
  let savedLang = 'ru';
  try { savedLang = localStorage.getItem('selectedLanguage') || 'ru'; } catch (e) {}
  translatePage(savedLang);

  // Обновляем флаг на кнопке, если сохранён не русский
  if (currentFlag && savedLang !== 'ru') {
    const savedFlagOption = document.querySelector(`.lang-option[data-lang="${savedLang}"] .flag`);
    if (savedFlagOption) currentFlag.src = savedFlagOption.src;
  }
});

